export function translateWorkName(name: string, lang: Lang): string {
  if (lang !== "en" || !name) return name;
  let s = String(name);
  if (WORK_NAME_EN[s]) return WORK_NAME_EN[s];
  for (const [from, to] of WORK_WORD_EN) {
    if (s.indexOf(from) !== -1) s = s.split(from).join(to);
  }
  return s
    .replace(/^Imagen\b/, "Image")
    .replace(/^Obra\b/, "Work")
    .replace(/^Ant\u00e1rtica\b/, "Antarctica")
    .replace(/^Lanzadera\b/, "Shuttle")
    .replace(/^Sauce\b/, "Willow")
    .replace(/^Piedra\b/, "Stone")
    .replace(/^Cabeza\b/, "Head")
    .replace(/^Caballo\b/, "Horse")
    .replace(/^Toro\b/, "Bull");
}

